-- 권왕: 몸동작 (애니메이션 파일 없이 관절 각도로 직접 만든다)
-- 관절 이름: R(골반·몸 전체), W(허리), N(목), RS·RE(오른 어깨·팔꿈치), LS·LE(왼 어깨·팔꿈치), RH·RK(오른 엉덩이·무릎), LH·LK
-- 각도는 도(degree) {x, y, z}. R만 {x, y, z, 옆, 위, 앞뒤} (앞은 -)
--   어깨 x+ = 팔을 앞으로 든다, z+ = 오른팔을 옆으로 (왼팔은 z-)
--   팔꿈치 x+ = 앞으로 굽힌다, 엉덩이 x+ = 다리를 앞으로, 무릎 x- = 굽힌다
--   허리 y+ = 몸을 왼쪽으로 튼다 (오른손 지르기), R x- = 앞으로 숙인다
-- 기술 하나 = 키프레임 목록 { t = 0~1 (기술 길이에 대한 비율), e = "snap"(빠르게 꽂힘) / 없으면 부드럽게, j = 관절 }
local Poses = {}

type Joints = { [string]: { number } }
type Key = { t: number, e: string?, j: Joints }

-- 좌우 뒤집기 (왼손 기술을 오른손 기술에서 만든다)
local SWAP = { RS = "LS", LS = "RS", RE = "LE", LE = "RE", RH = "LH", LH = "RH", RK = "LK", LK = "RK" }
local function mirrorJ(j: Joints): Joints
	local out: Joints = {}
	for name, v in pairs(j) do
		local to = SWAP[name] or name
		local m = { v[1], -(v[2] or 0), -(v[3] or 0) }
		if name == "R" then
			m = { v[1], -(v[2] or 0), -(v[3] or 0), -(v[4] or 0), v[5] or 0, v[6] or 0 }
		end
		out[to] = m
	end
	return out
end
local function mirror(keys: { Key }): { Key }
	local out = {}
	for _, k in ipairs(keys) do
		table.insert(out, { t = k.t, e = k.e, j = mirrorJ(k.j) })
	end
	return out
end

